<script setup lang="ts">
import { ref } from 'vue'
import { db } from '../lib/db'
import { settings } from '../lib/settings'
import { askAboutSpending } from '../lib/gemini'

const question = ref('')
const answer = ref('')
const busy = ref(false)
const error = ref('')

const examples = [
  'How much did I spend on dining last month?',
  'What are my biggest recurring charges?',
  'Which merchant did I spend the most at this year?',
  'How does my grocery spending compare month to month?',
]

/** compact CSV of confirmed transactions for the model (recent first, capped) */
async function buildCsv(): Promise<{ csv: string; count: number }> {
  const rows = await db.transactions.where('status').equals('confirmed').toArray()
  rows.sort((a, b) => b.date.localeCompare(a.date))
  const capped = rows.slice(0, 1200)
  const lines = capped.map(
    (t) =>
      `${t.date},${t.merchant.replace(/,/g, ' ')},${t.category},${t.direction},${(t.amountCents / 100).toFixed(2)}`,
  )
  return { csv: `date,merchant,category,direction,amount\n${lines.join('\n')}`, count: capped.length }
}

async function ask(q?: string) {
  const query = (q ?? question.value).trim()
  if (!query || busy.value) return
  question.value = query
  error.value = ''
  answer.value = ''
  busy.value = true
  try {
    if (!settings.geminiApiKey) throw new Error('Add your Gemini API key in Settings first')
    const { csv, count } = await buildCsv()
    if (count === 0) throw new Error('No transactions yet — add some or run a sync first')
    answer.value = await askAboutSpending(query, csv, settings.geminiApiKey, settings.geminiModel)
  } catch (e) {
    error.value = (e as Error).message
  } finally {
    busy.value = false
  }
}
</script>

<template>
  <div class="max-w-3xl">
    <h1 class="text-xs uppercase tracking-[0.2em] mb-1">Ask your money</h1>
    <p class="text-xs text-muted mb-4 leading-relaxed">
      Ask anything about your spending in plain English. Gemini answers from your on-device
      transactions — nothing is stored anywhere else.
    </p>

    <div class="flex gap-2 mb-3">
      <input
        v-model="question"
        placeholder="e.g. how much on groceries in June?"
        @keydown.enter="ask()"
      />
      <button class="btn btn-accent shrink-0" :disabled="busy" @click="ask()">
        {{ busy ? 'Thinking…' : 'Ask' }}
      </button>
    </div>

    <div class="flex flex-wrap gap-2 mb-5">
      <button
        v-for="ex in examples"
        :key="ex"
        class="border border-line px-2.5 py-1 text-[11px] text-muted hover:border-ink hover:text-ink cursor-pointer text-left"
        :disabled="busy"
        @click="ask(ex)"
      >
        {{ ex }}
      </button>
    </div>

    <div v-if="error" class="card p-4 text-xs text-accent mb-4">{{ error }}</div>

    <div v-if="answer" class="card p-4">
      <div class="label mb-2">Answer</div>
      <p class="text-sm leading-relaxed whitespace-pre-wrap">{{ answer }}</p>
    </div>
    <div v-else-if="busy" class="card p-4 text-xs text-muted">
      Reading your transactions and thinking…
    </div>

    <p class="text-[10px] text-muted mt-4 leading-relaxed">
      Answers are generated by AI from the most recent ~1,200 transactions and can be wrong — check
      the numbers against your ledger for anything important.
    </p>
  </div>
</template>
